// Renders the ZhaoXi app's clay 3D icons (frontend/apps/customer-mobile/src/ui/service-icons.tsx) to static
// SVG strings for the partner web, so both channels share one icon set. Gradient ids are prefixed per icon
// so several icons on one page never share a gradient by accident.
//   node scripts/gen-art3d.mjs   (from frontend/apps/partner) → frontend/packages/ui/src/art3d-data.ts
import { build } from "esbuild";
import { writeFileSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "../../customer-mobile/src/ui/service-icons.tsx");
// Bundled next to this script so the bundle resolves react / react-dom from the workspace node_modules.
const out = join(here, ".art3d-entry.mjs");
const entry = `
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { Art3D, ServiceArt } from ${JSON.stringify(source)};
export function render(kinds, codes) {
  const art = Object.fromEntries(kinds.map((k) => [k, renderToStaticMarkup(createElement(Art3D, { kind: k, size: 64 }))]));
  const service = Object.fromEntries(codes.map((c) => [c, renderToStaticMarkup(createElement(ServiceArt, { code: c, size: 64 }))]));
  return { art, service };
}`;
await build({
  stdin: { contents: entry, resolveDir: here, loader: "jsx" },
  bundle: true, format: "esm", platform: "node", outfile: out, jsx: "automatic", logLevel: "error",
  alias: { "react-native-svg": join(here, "art3d-shims/svg.js"), "react-native": join(here, "art3d-shims/rn.js"), "expo-image": join(here, "art3d-shims/rn.js") },
  loader: { ".png": "empty" },
  external: ["react", "react-dom", "react-dom/server"],
  nodePaths: [join(here, "../../../node_modules")],
});
const KINDS = ["orders","favorites","history","coupons","notifications","language","security","emergency","push","promotions","help","feedback","pin","people","store","sparkle","heart","bookmark","scooter","truck","compass","card","calendar","check","search","pencil","play","hourglass","gift","cooking","delivery","clipboard","medal","cancel","wallet","attention","bed","bath","area"];
const CODES = ["food","housing","visa","car-rental","translation","travel","payment","community","market","emergency","store"];
const { render } = await import(pathToFileURL(out).href);
rmSync(out);
const { art, service } = render(KINDS, CODES);
const scope = (name, svg) => {
  const tag = "zx3d-" + name.replace(/[^a-z0-9]+/gi, "-");
  return svg.replace(/ (width|height)="64"/g, "").replace(/id="([^"]+)"/g, (_, id) => `id="${tag}-${id}"`).replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${tag}-${id})`);
};
const lines = [
  "// Generated by scripts/gen-art3d.mjs from the ZhaoXi app's clay icons — do not edit by hand.",
  `export const ART3D = {\n${Object.entries(art).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(scope(k, v))},`).join("\n")}\n} as const;`,
  `export type Art3DKind = keyof typeof ART3D;`,
  `export const SERVICE_ART = {\n${Object.entries(service).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(scope("svc-" + k, v))},`).join("\n")}\n} as const;`,
  `export type ServiceArtCode = keyof typeof SERVICE_ART;`,
  "",
];
writeFileSync(join(here, "../../../packages/ui/src/art3d-data.ts"), lines.join("\n"));
console.log(`art3d: ${Object.keys(art).length} icons, ${Object.keys(service).length} service illustrations`);
